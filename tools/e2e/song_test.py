import asyncio
from playwright.async_api import async_playwright
OUT='/tmp/claude-0/song'
import os; os.makedirs(OUT, exist_ok=True)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required'])
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, has_touch=True, is_mobile=True, device_scale_factor=2)
        pg = await ctx.new_page()
        logs = []
        pg.on('console', lambda m: logs.append(f'{m.type}: {m.text}') if m.type in ('error','warning') else None)
        pg.on('pageerror', lambda e: logs.append(f'PAGEERROR: {e}'))
        await pg.goto('http://localhost:8765/#practice')
        await pg.wait_for_selector('body[data-ready]')
        await pg.wait_for_timeout(700)
        await pg.click("text=Let's begin")
        await pg.set_input_files('#song-file', '/tmp/song.musicxml')
        await pg.wait_for_timeout(600)
        print('toast:', await pg.evaluate("() => [...document.querySelectorAll('.toast-msg')].map(t => t.textContent)"))
        song = await pg.evaluate("() => JSON.parse(localStorage.getItem('petalkeys.songs'))[0].song")
        print('song:', song['title'], song['key'], song['time'], song['staves'], [ (m['label'], m['start'], m['beats']) for m in song['measures'] ])
        print('notes:', len(song['notes']), [(n['letter'], n['acc'], n['octave'], n['beat'], n['dur'], n.get('tieStart'), n.get('tieStop')) for n in song['notes'][:8]])
        await pg.screenshot(path=f'{OUT}/1-practice.png')
        await pg.click('.song-main')
        await pg.wait_for_timeout(700)
        await pg.screenshot(path=f'{OUT}/2-wait.png')
        steps = await pg.evaluate("() => { const o = document.querySelector('#song-sec'); return [...o.options].map(x => x.textContent) }")
        print('sections:', steps)
        # whole song
        await pg.select_option('#song-sec', '0')
        await pg.wait_for_timeout(500)
        await pg.screenshot(path=f'{OUT}/3-whole.png')
        # play through in wait mode: read expected from the hint keys
        for i in range(40):
            hint = await pg.evaluate("() => [...document.querySelectorAll('.ex-kb .key.hint')].map(k => +k.dataset.midi)")
            if not hint: break
            if i == 3:
                await pg.evaluate("(m) => { const b = window.__petalKeys.bus; b.noteOn(m, .7, performance.now(), 'midi'); b.noteOff(m, performance.now(), 'midi'); }", hint[0] + 2)
                await pg.wait_for_timeout(150)
                await pg.screenshot(path=f'{OUT}/4-wrong.png')
            for m in hint:
                await pg.evaluate("(m) => { const b = window.__petalKeys.bus; b.noteOn(m, .7, performance.now(), 'midi'); b.noteOff(m, performance.now(), 'midi'); }", m)
            await pg.wait_for_timeout(120)
            if i == 6: await pg.screenshot(path=f'{OUT}/5-mid.png')
        await pg.wait_for_timeout(500)
        print('steps played:', i, '| feedback:', await pg.text_content('.ex-feedback'))
        await pg.screenshot(path=f'{OUT}/6-done.png')
        # play along on part 1
        await pg.click('text=Play along')
        await pg.wait_for_timeout(400)
        await pg.screenshot(path=f'{OUT}/7-play-idle.png')
        await pg.close()
        # desktop look
        pg = await ctx.browser.new_page(viewport={'width': 1200, 'height': 800})
        await pg.goto('http://localhost:8765/#practice')
        await pg.wait_for_selector('body[data-ready]')
        await pg.wait_for_timeout(600)
        await pg.keyboard.press('Escape')
        await pg.set_input_files('#song-file', '/tmp/song.musicxml')
        await pg.wait_for_timeout(400)
        await pg.click('.song-main')
        await pg.wait_for_timeout(500)
        await pg.select_option('#song-sec', '0')
        await pg.wait_for_timeout(500)
        await pg.screenshot(path=f'{OUT}/8-desk.png')
        print('\n'.join(logs) if logs else 'no console errors')
        await b.close()
asyncio.run(main())

async def rush_from_songs():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required'])
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, has_touch=True, is_mobile=True, device_scale_factor=2)
        pg = await ctx.new_page()
        logs = []
        pg.on('pageerror', lambda e: logs.append(f'PAGEERROR: {e}'))
        pg.on('console', lambda m: logs.append(f'{m.type}: {m.text}') if m.type in ('error','warning') else None)
        await pg.goto('http://localhost:8765/#practice')
        await pg.wait_for_selector('body[data-ready]')
        await pg.wait_for_timeout(600)
        await pg.click("text=Let's begin")
        await pg.set_input_files('#song-file', '/tmp/song.musicxml')
        await pg.wait_for_timeout(400)
        await pg.evaluate("() => window.__petalKeys.startSession({ title: 'Note Rush', steps: [{ type: 'rush', clef: 'treble', pool: ['C4','D4','E4'], level: 1, bars: 1, tempo: 90, count: 2, source: 'songs' }] })")
        await pg.wait_for_timeout(700)
        print('rush feedback:', await pg.text_content('.ex-feedback'))
        await pg.screenshot(path=f'{OUT}/9-rush-song.png')
        await pg.click('.ex-actions .btn-primary')
        await pg.wait_for_timeout(200)
        await pg.evaluate("""() => { const a = window.__petalKeys; const exp = a.debug.rush.expected; exp.forEach((e) => { setTimeout(() => { a.bus.noteOn(e.midi, .7, performance.now(), 'midi'); a.bus.noteOff(e.midi, performance.now(), 'midi'); }, Math.max(0, e.t - performance.now() + 10)); }); }""")
        await pg.wait_for_timeout(6500)
        await pg.screenshot(path=f'{OUT}/10-rush-song-result.png')
        print('chips:', await pg.evaluate("() => [...document.querySelectorAll('.score-chip')].map(c => c.textContent)"))
        # whole song desktop after fix
        pg2 = await b.new_page(viewport={'width': 1200, 'height': 800})
        await pg2.goto('http://localhost:8765/#practice')
        await pg2.wait_for_selector('body[data-ready]')
        await pg2.wait_for_timeout(500)
        await pg2.keyboard.press('Escape')
        await pg2.set_input_files('#song-file', '/tmp/song.musicxml')
        await pg2.wait_for_timeout(3500)
        await pg2.click('.song-main')
        await pg2.wait_for_timeout(400)
        await pg2.select_option('#song-sec', '0')
        await pg2.wait_for_timeout(400)
        await pg2.screenshot(path=f'{OUT}/11-desk.png')
        print('\n'.join(logs) if logs else 'no console errors')
        await b.close()
asyncio.run(rush_from_songs())
