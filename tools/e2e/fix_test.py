import asyncio
from playwright.async_api import async_playwright
OUT='/tmp/claude-0/fix'
import os; os.makedirs(OUT, exist_ok=True)
def check(c, m): print(('PASS ' if c else 'FAIL ') + m)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--autoplay-policy=no-user-gesture-required'])
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, has_touch=True, is_mobile=True, device_scale_factor=2)
        pg = await ctx.new_page()
        logs = []
        pg.on('console', lambda m: logs.append(f'{m.type}: {m.text}') if m.type in ('error','warning') else None)
        pg.on('pageerror', lambda e: logs.append(f'PAGEERROR: {e}'))
        await pg.goto('http://localhost:8765/#practice')
        await pg.wait_for_selector('body[data-ready]')
        await pg.wait_for_timeout(600)
        await pg.click("text=Let's begin")
        await pg.set_input_files('#song-file', '/tmp/song.musicxml')
        await pg.wait_for_timeout(400)
        await pg.click('.song-main')
        await pg.wait_for_timeout(500)
        await pg.select_option('#song-sec', '2')  # bars 5-8
        await pg.click('.seg-btn:has-text("Play along")')
        await pg.wait_for_timeout(300)
        hints_idle = await pg.evaluate("() => [...document.querySelectorAll('.ex-kb .key.hint')].map(k => +k.dataset.midi)")
        check(hints_idle == [62], f'play-along shows first key hint {hints_idle}')
        await pg.click('.ex-actions .btn-primary')  # Go
        await pg.wait_for_timeout(3600)
        n = await pg.evaluate("() => window.__petalKeys.audio.clicks.length")
        check(n > 5, f'metronome clicks scheduled while playing ({n})')
        hints_play = await pg.evaluate("() => [...document.querySelectorAll('.ex-kb .key.hint')].map(k => +k.dataset.midi)")
        await pg.screenshot(path=f'{OUT}/1-play-hints.png')
        check(len(hints_play) == 1, f'hint follows the music during play {hints_play}')
        # the bug: switch to wait mid-play
        await pg.click('.seg-btn:has-text("Wait")')
        await pg.wait_for_timeout(200)
        n2 = await pg.evaluate("() => window.__petalKeys.audio.clicks.length")
        check(n2 == 0, f'switching to Wait stops the metronome (clicks left: {n2})')
        # wait mode: play two right notes then a wrong one, then restart with R
        for m in (62, 67):
            await pg.evaluate("(m) => { const b = window.__petalKeys.bus; b.noteOn(m, .7, performance.now(), 'midi'); b.noteOff(m, performance.now(), 'midi'); }", m)
        await pg.evaluate("() => { const b = window.__petalKeys.bus; b.noteOn(60, .7, performance.now(), 'midi'); b.noteOff(60, performance.now(), 'midi'); }")
        fb = await pg.text_content('.ex-feedback')
        await pg.keyboard.press('r')
        await pg.wait_for_timeout(200)
        h2 = await pg.evaluate("() => [...document.querySelectorAll('.ex-kb .key.hint')].map(k => +k.dataset.midi)")
        check(h2 == [62], f'R restarts wait mode at the first note {h2} (feedback before: "{fb}")')
        # hints off in wait
        await pg.click('label:has(#song-hints)')
        await pg.wait_for_timeout(100)
        h3 = await pg.evaluate("() => document.querySelectorAll('.ex-kb .key.hint').length")
        check(h3 == 0, 'key hints toggle off in wait mode')
        await pg.click('label:has(#song-names)')
        await pg.wait_for_timeout(200)
        names = await pg.evaluate("() => document.querySelectorAll('.staff-svg .note-name').length")
        check(names > 3, f'note names shown ({names})')
        await pg.screenshot(path=f'{OUT}/2-wait-names.png')
        # learn a restart pad (drum channel note 36) via simulated MIDI
        await pg.evaluate("() => { const a = window.__petalKeys; a.midi.status = 'connected'; }")
        await pg.click('.chip-btn')
        await pg.wait_for_timeout(300)
        await pg.click('text=Listen for button')
        await pg.evaluate("() => window.__petalKeys.midi._onMessage({ data: [0x99, 36, 100], timeStamp: performance.now() })")
        await pg.wait_for_timeout(300)
        trig = await pg.evaluate("() => window.__petalKeys.store.getLocal('restartTrigger')")
        check(trig == {'type': 'note', 'ch': 9, 'num': 36}, f'restart pad learned {trig}')
        await pg.screenshot(path=f'{OUT}/3-learned.png')
        # play-along, finish, then restart with the pad from the results screen
        await pg.click('.seg-btn:has-text("Play along")')
        await pg.evaluate("() => window.__petalKeys.midi._onMessage({ data: [0x99, 36, 100], timeStamp: performance.now() })")
        await pg.wait_for_timeout(150)
        fb2 = await pg.text_content('.ex-feedback')
        check('count-in' in fb2, f'pad starts play-along straight away: "{fb2}"')
        # finish quickly: force end
        await pg.evaluate("() => { const s = window.__petalKeys.session; }")
        await pg.click('.ex-actions button:has-text("Stop")', timeout=5000)
        await pg.wait_for_timeout(150)
        tempo = await pg.evaluate("() => +document.querySelector('.tempo-val').textContent")
        print('tempo', tempo)
        await pg.click('.ex-actions .btn-primary')  # Go
        await pg.wait_for_timeout(200)
        # simulate a whole run by jumping time: wait for it to end at tempo
        await pg.wait_for_timeout(int((16 + 4) * 60000 / max(tempo, 1)) + 1200)
        res = await pg.evaluate("() => !document.querySelector('.score-box').hidden")
        check(res, 'play-along reaches its results')
        await pg.screenshot(path=f'{OUT}/4-result.png')
        await pg.evaluate("() => window.__petalKeys.midi._onMessage({ data: [0x99, 36, 100], timeStamp: performance.now() })")
        await pg.wait_for_timeout(150)
        fb3 = await pg.text_content('.ex-feedback')
        check('count-in' in fb3, f'pad restarts from the results screen: "{fb3}"')
        # pad note must not sound or count
        played = await pg.evaluate("() => window.__petalKeys.bus.held()")
        check(played == [], 'restart pad does not play a note')
        await pg.keyboard.press('Escape')
        await pg.wait_for_timeout(200)
        n3 = await pg.evaluate("() => window.__petalKeys.audio.clicks.length")
        check(n3 == 0, f'closing stops the metronome ({n3})')
        print('\n'.join(logs) if logs else 'no console errors')
        await b.close()
asyncio.run(main())
