// Build helper. Run with: node tools/build.mjs
//
// 1. Writes sw.js with the list of files to keep offline and a version based
//    on their contents (so phones pick up changes automatically).
// 2. Optionally (--preview <dir>) writes a single-page preview with the CSS
//    and a bundled script inlined (needs `npm i esbuild` somewhere).

import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, copyFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

const files = [
  'index.html',
  'manifest.webmanifest',
  ...walk(join(ROOT, 'css')).map((p) => relative(ROOT, p)),
  ...walk(join(ROOT, 'js')).map((p) => relative(ROOT, p)),
  ...walk(join(ROOT, 'assets')).map((p) => relative(ROOT, p)),
  ...walk(join(ROOT, 'icons')).filter((p) => !p.endsWith('-src.svg')).map((p) => relative(ROOT, p)),
].map((p) => p.split('\\').join('/')).sort();

const hash = createHash('sha1');
for (const f of files) hash.update(f).update(readFileSync(join(ROOT, f)));
const version = hash.digest('hex').slice(0, 10);

const sw = `// Petal Keys service worker: keeps the app working offline (e.g. on the MRT).
// Generated by tools/build.mjs — rerun it after changing files.
const VERSION = '${version}';
const CACHE = 'petal-keys-' + VERSION;
const PRECACHE = ${JSON.stringify(['./', ...files.map((f) => './' + f)], null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(PRECACHE))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('petal-keys-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    event.respondWith(
      caches.match('./index.html').then((hit) => hit || fetch(req)).catch(() => caches.match('./index.html')),
    );
    return;
  }
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const hit = await cache.match(req, { ignoreSearch: true });
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok && res.type === 'basic') cache.put(req, res.clone());
      return res;
    }),
  );
});
`;
writeFileSync(join(ROOT, 'sw.js'), sw);
console.log(`sw.js written: ${files.length} files, version ${version}`);

// ---------- optional preview build ----------
const i = process.argv.indexOf('--preview');
if (i > 0) {
  const outDir = process.argv[i + 1];
  const esbuildPath = process.argv[i + 2];
  const { build } = await import(esbuildPath || 'esbuild');
  const res = await build({
    entryPoints: [join(ROOT, 'js/main.js')],
    bundle: true,
    format: 'iife',
    target: ['chrome100', 'firefox100'],
    write: false,
    minify: false,
    legalComments: 'none',
  });
  const js = res.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
  const css = readFileSync(join(ROOT, 'css/fonts.css'), 'utf8') + '\n' + readFileSync(join(ROOT, 'css/app.css'), 'utf8');
  const page = `<title>Petal Keys</title>
<meta name="claude:viewport-fit-sides" content="cover">
<meta name="theme-color" content="#f3f9f6">
<style>
${css}
</style>
<div id="app"></div>
<script>
${js}
</script>
`;
  mkdirSync(join(outDir, 'assets/piano'), { recursive: true });
  writeFileSync(join(outDir, 'petal-keys.html'), page);
  for (const f of files.filter((f) => f.startsWith('assets/piano/'))) copyFileSync(join(ROOT, f), join(outDir, f));
  console.log(`preview written to ${outDir} (${Math.round(page.length / 1024)} KB page)`);
}
